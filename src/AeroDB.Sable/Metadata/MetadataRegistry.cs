using System.Collections.Concurrent;
using System.Diagnostics;
using System.Globalization;

namespace AeroDB.Sable.Metadata;

/// <summary>
/// Compile-time schema for a document property, emitted by the AeroDB.Sable source generator.
/// Used by <c>SchemaManager</c> to emit DEFINE FIELD statements without reflection.
/// </summary>
public readonly record struct FieldSchema(
    string Name,
    string SurrealType,
    bool CanRead,
    bool CanWrite)
{
    /// <summary>
    /// Whether this object-shaped field admits undeclared nested properties while
    /// its containing table remains SCHEMAFULL.
    /// </summary>
    public bool IsFlexible { get; init; }

    /// <summary>The reversible encryption algorithm, or null for a clear field.</summary>
    public EncryptionAlgorithm? EncryptionAlgorithm { get; init; }
}

/// <summary>
/// Generated or fluent runtime access to one encrypted domain property.
/// </summary>
public sealed record EncryptedFieldDescriptor(
    string PropertyName,
    Type ClrType,
    string CodecId,
    EncryptionAlgorithm Algorithm,
    Func<object, object?> GetValue,
    Action<object, object?> SetValue);

/// <summary>Generated or fluent runtime metadata for one blind-indexed field.</summary>
public sealed record BlindIndexDescriptor(
    string PropertyName,
    BlindIndexAlgorithm Algorithm,
    BlindIndexNormalizer Normalizer,
    string? StorageFieldName,
    Func<object, string?> GetValue);

/// <summary>
/// Generic metadata interface for a document type.
/// </summary>
public interface ITypeMetadata
{
    /// <summary>
    /// The snake_case table name for this document type.
    /// </summary>
    string TableName { get; }

    /// <summary>
    /// Whether this document type has a TenantId string property.
    /// </summary>
    bool HasTenantId { get; }

    /// <summary>
    /// Whether this document type has a version field (via <see cref="IVersioned"/> or <see cref="VersionAttribute"/>).
    /// </summary>
    bool HasVersion { get; }

    /// <summary>
    /// Whether this document type implements <see cref="IDocumentMetadata"/> for auto-tracked
    /// audit timestamps (CreatedAt, LastModified).
    /// </summary>
    bool HasDocumentMetadata { get; }

    /// <summary>
    /// Whether this document type has an associated <see cref="EventProjection{T}"/> dispatch.
    /// When true, the source generator has emitted (or can emit) a type-switch ApplyEvents override
    /// for the projection class, avoiding runtime reflection.
    /// </summary>
    bool HasEventProjectionDispatch { get; }

    /// <summary>
    /// The name of the version property, or null if this type has no version field.
    /// Generated metadata provides this directly from compile-time analysis, avoiding reflection.
    /// </summary>
    string? VersionFieldName { get; }

    /// <summary>Untyped version accessor delegate for generated types. Null if no version field.</summary>
    Func<object, long>? GetVersionAccessor { get; }

    /// <summary>Untyped version setter delegate for generated types. Null if no version field.</summary>
    Action<object, long>? SetVersionAccessor { get; }

    /// <summary>
    /// The CLR identity type declared by the document, or null when the document has
    /// no conventional identity property.
    /// </summary>
    Type? IdentityType { get; }

    /// <summary>
    /// Untyped CLR identity accessor for generated types. The original CLR type is
    /// preserved so numeric identities remain numeric SurrealDB record keys.
    /// Null if no identity property exists.
    /// </summary>
    Func<object, object?>? GetIdentityAccessor { get; }

    /// <summary>
    /// Compile-time list of public readable/writable properties (excluding Id).
    /// Emitted by the source generator; null when metadata is generated by a legacy
    /// source generator that predates field schema support.
    /// </summary>
    IReadOnlyList<FieldSchema>? Fields { get; }

    /// <summary>Source-generated encrypted-property accessors for this type.</summary>
    IReadOnlyList<EncryptedFieldDescriptor>? EncryptedFields { get; }

    /// <summary>Source-generated blind-index accessors for this type.</summary>
    IReadOnlyList<BlindIndexDescriptor>? BlindIndexes => null;
}

/// <summary>
/// Typed metadata interface for a specific document type T.
/// Generated metadata classes implement this interface.
/// </summary>
public interface ITypeMetadata<T> : ITypeMetadata
{
    /// <summary>
    /// Gets the tenant ID from the entity, or null if not tenant-aware.
    /// </summary>
    string? GetTenantId(T entity);

    /// <summary>
    /// Gets the current version from the entity, or -1 if no version field.
    /// </summary>
    long GetVersion(T entity);

    /// <summary>
    /// Sets the version on the entity (increments it).
    /// </summary>
    void SetVersion(T entity, long version);

    /// <summary>
    /// Extracts the CLR identity from the entity's Id property without converting it
    /// to a string. Existing <see cref="SurrealDb.Net.Models.RecordId"/> values are
    /// returned unchanged.
    /// </summary>
    object? GetIdentity(T entity);

    /// <summary>Sets the tenant ID on the entity, or no-op if not tenant-aware.</summary>
    void SetTenantId(T entity, string? tenantId);
}

/// <summary>
/// A source-generated, closed materializer for one document shape. The delegate
/// is registered by a module initializer, so hot read paths do not need to
/// discover or invoke entity members through reflection.
/// </summary>
public delegate T GeneratedMaterializer<T>(
    IReadOnlyDictionary<string, object?> values,
    SchemaOptions? schema,
    EnumStorage enumStorage);

/// <summary>
/// Central registry for per-type metadata generated by the AeroDB.Sable source generator.
/// Generated <c>{Type}Metadata</c> classes self-register in their static constructors.
/// Runtime code queries the registry to avoid reflection in hot paths.
/// </summary>
public static class MetadataRegistry
{
    private static readonly DiagnosticListener MaterializationDiagnostics = new("AeroDB.Sable.Materialization");
    private static readonly ConcurrentDictionary<Type, ITypeMetadata> _cache = new();
    private static readonly ConcurrentDictionary<Type, object> _generatedMaterializers = new();
    private static readonly ConcurrentBag<RelationshipCandidate> _relationshipCandidates = new();

    internal static DiagnosticListener GeneratedMaterializationDiagnostics => MaterializationDiagnostics;

    /// <summary>
    /// Called by generated code to register metadata for a type.
    /// Thread-safe; intended to be called from static constructors during assembly load.
    /// </summary>
    public static void Register<T>(ITypeMetadata<T> metadata)
    {
        _cache[typeof(T)] = metadata;
    }

    /// <summary>
    /// Attempts to retrieve metadata for the given type.
    /// Returns null if no metadata has been registered (e.g., the type is not a Record subclass).
    /// </summary>
    public static ITypeMetadata? TryGet(Type type)
    {
        _cache.TryGetValue(type, out var metadata);
        return metadata;
    }

    /// <summary>
    /// Gets the metadata for type T, or null if not registered.
    /// </summary>
    public static ITypeMetadata<T>? TryGet<T>()
    {
        if (_cache.TryGetValue(typeof(T), out var metadata) && metadata is ITypeMetadata<T> typed)
            return typed;
        return null;
    }

    /// <summary>Registers a source-generated materializer for a supported document shape.</summary>
    public static void RegisterGeneratedMaterializer<T>(GeneratedMaterializer<T> materializer)
    {
        ArgumentNullException.ThrowIfNull(materializer);
        _generatedMaterializers[typeof(T)] = materializer;
    }

    /// <summary>
    /// Materializes one record through its generated delegate when the concrete
    /// document shape opted in. Unsupported shapes deliberately return false so
    /// callers retain the established legacy materializer.
    /// </summary>
    public static bool TryMaterialize<T>(
        IReadOnlyDictionary<string, object?> values,
        SchemaOptions? schema,
        EnumStorage enumStorage,
        out T materialized)
    {
        if (_generatedMaterializers.TryGetValue(typeof(T), out var registered)
            && registered is GeneratedMaterializer<T> reader)
        {
            materialized = reader(values, schema, enumStorage);
            if (MaterializationDiagnostics.IsEnabled("generated"))
                MaterializationDiagnostics.Write("generated", new { Type = typeof(T).FullName, Path = "generated" });
            return true;
        }

        materialized = default!;
        if (MaterializationDiagnostics.IsEnabled("generated-dispatch-miss"))
            MaterializationDiagnostics.Write("generated-dispatch-miss", new { Type = typeof(T).FullName, Path = "legacy" });
        return false;
    }

    /// <summary>
    /// Reads and converts one supported generated property. The field name is
    /// resolved at runtime so configured naming policies and field overrides
    /// remain authoritative over the generator's CLR property names.
    /// </summary>
    public static bool TryReadValue<T>(
        IReadOnlyDictionary<string, object?> values,
        Type documentType,
        string propertyName,
        SchemaOptions? schema,
        EnumStorage enumStorage,
        out T value)
    {
        if (!TryReadRawValue(values, documentType, propertyName, schema, out var raw))
        {
            value = default!;
            return false;
        }

        value = ReadScalar<T>(raw, enumStorage);
        return true;
    }

    /// <summary>Gets a persisted field without inspecting entity members.</summary>
    public static bool TryReadRawValue(
        IReadOnlyDictionary<string, object?> values,
        Type documentType,
        string propertyName,
        SchemaOptions? schema,
        out object? value)
    {
        var fieldName = MetadataDispatch.GetFieldName(documentType, propertyName, schema);
        return TryGetValue(values, fieldName, out value)
            || TryGetValue(values, propertyName, out value);
    }

    /// <summary>Converts one scalar value for source-generated code.</summary>
    public static T ReadScalar<T>(object? raw, EnumStorage enumStorage)
    {
        if (raw is null)
        {
            if (Nullable.GetUnderlyingType(typeof(T)) is null && typeof(T).IsValueType)
                throw new InvalidOperationException($"Cannot assign null to non-nullable '{typeof(T).FullName}'.");
            return default!;
        }

        var target = Nullable.GetUnderlyingType(typeof(T)) ?? typeof(T);
        object? converted;
        if (target.IsEnum)
        {
            if (raw is T typed)
                return typed;

            if (raw is string name)
            {
                if (enumStorage == EnumStorage.AsInteger)
                    throw new InvalidOperationException($"Expected a numeric value for enum '{target.FullName}'.");

                converted = Enum.Parse(target, name, ignoreCase: true);
            }
            else if (IsNumeric(raw))
            {
                var underlying = Enum.GetUnderlyingType(target);
                if (IsIntegralType(underlying) && IsFractionalNumeric(raw))
                    throw new InvalidOperationException($"Expected an integral numeric value for enum '{target.FullName}'.");

                converted = Enum.ToObject(target, Convert.ChangeType(raw, underlying, CultureInfo.InvariantCulture)!);
            }
            else
            {
                throw new InvalidOperationException($"Expected a string or numeric value for enum '{target.FullName}'.");
            }
        }
        else if (raw is T typed)
        {
            return typed;
        }
        else if (target == typeof(Guid))
        {
            converted = raw is Guid guid ? guid : raw is string text
                ? Guid.Parse(text)
                : throw new InvalidOperationException($"Expected a Guid or string value for '{typeof(T).FullName}'.");
        }
        else if (target == typeof(DateTimeOffset))
        {
            converted = raw is DateTimeOffset offset
                ? offset.ToUniversalTime()
                : raw is DateTime time
                    ? new DateTimeOffset(DateTime.SpecifyKind(time, DateTimeKind.Utc))
                    : raw is string text
                        ? DateTimeOffset.Parse(text, CultureInfo.InvariantCulture,
                            DateTimeStyles.AssumeUniversal | DateTimeStyles.AdjustToUniversal)
                        : throw new InvalidOperationException($"Expected a date-time value for '{typeof(T).FullName}'.");
        }
        else if (target == typeof(DateTime))
        {
            var dateTime = raw is DateTime time
                ? time
                : raw is string text
                    ? DateTime.Parse(text, CultureInfo.InvariantCulture,
                        DateTimeStyles.AssumeUniversal | DateTimeStyles.AdjustToUniversal)
                    : throw new InvalidOperationException($"Expected a date-time value for '{typeof(T).FullName}'.");
            converted = DateTime.SpecifyKind(dateTime, DateTimeKind.Utc);
        }
        else if (target == typeof(byte[]))
        {
            converted = raw is byte[] bytes
                ? bytes
                : raw is IEnumerable<byte> sequence
                    ? sequence.ToArray()
                    : throw new InvalidOperationException($"Expected a byte sequence for '{typeof(T).FullName}'.");
        }
        else if (target == typeof(decimal) && raw is string decimalText)
        {
            converted = decimal.Parse(decimalText, NumberStyles.Number, CultureInfo.InvariantCulture);
        }
        else if (target == typeof(string))
        {
            converted = raw as string
                ?? throw new InvalidOperationException($"Expected a string value for '{typeof(T).FullName}'.");
        }
        else if (target == typeof(bool))
        {
            converted = raw is bool boolean
                ? boolean
                : throw new InvalidOperationException($"Expected a Boolean value for '{typeof(T).FullName}'.");
        }
        else if (target.IsPrimitive || target == typeof(decimal))
        {
            if (IsIntegralType(target) && IsFractionalNumeric(raw))
                throw new InvalidOperationException($"Expected an integral numeric value for '{typeof(T).FullName}'.");

            converted = IsNumeric(raw)
                ? Convert.ChangeType(raw, target, CultureInfo.InvariantCulture)
                : throw new InvalidOperationException($"Expected a numeric value for '{typeof(T).FullName}'.");
        }
        else
        {
            throw new InvalidOperationException(
                $"No generated conversion is available for '{typeof(T).FullName}'.");
        }

        return (T)converted!;
    }

    /// <summary>
    /// Reads a native Surreal record identity without using entity metadata at
    /// runtime. The table/key separator is the first colon: string keys may
    /// themselves contain later colons and must remain lossless.
    /// </summary>
    public static bool TryReadIdentity<T>(
        IReadOnlyDictionary<string, object?> values,
        Type documentType,
        SchemaOptions? schema,
        out T value)
    {
        var fieldName = MetadataDispatch.GetFieldName(documentType, "Id", schema);
        if (!TryGetValue(values, fieldName, out var raw)
            && !TryGetValue(values, "id", out raw)
            && !TryGetValue(values, "Id", out raw))
        {
            value = default!;
            return false;
        }

        if (raw is null)
            throw new InvalidOperationException($"Cannot assign a null record identity to '{typeof(T).FullName}'.");

        var text = Convert.ToString(raw, CultureInfo.InvariantCulture);
        var separator = text?.IndexOf(':') ?? -1;
        var key = separator >= 0 ? text![(separator + 1)..] : text;

        var target = Nullable.GetUnderlyingType(typeof(T)) ?? typeof(T);
        if (key is not null && IsIdentityNumericType(target))
        {
            value = (T)Convert.ChangeType(key, target, CultureInfo.InvariantCulture);
            return true;
        }

        if (key is not null && target == typeof(Guid))
        {
            value = (T)(object)Guid.Parse(key);
            return true;
        }

        return TryReadValue(
            new Dictionary<string, object?> { ["value"] = key },
            typeof(IdentityValue),
            "value",
            schema: null,
            EnumStorage.AsString,
            out value);
    }

    private sealed class IdentityValue;

    /// <summary>Records that the central reader is about to use the legacy materializer.</summary>
    internal static void RecordLegacyMaterialization<T>()
    {
        if (MaterializationDiagnostics.IsEnabled("legacy"))
            MaterializationDiagnostics.Write("legacy", new { Type = typeof(T).FullName, Path = "legacy" });
    }

    private static bool IsNumeric(object value)
        => value is byte or sbyte or short or ushort or int or uint or long or ulong or float or double or decimal;

    private static bool IsIdentityNumericType(Type type)
        => type == typeof(byte) || type == typeof(sbyte)
            || type == typeof(short) || type == typeof(ushort)
            || type == typeof(int) || type == typeof(uint)
            || type == typeof(long) || type == typeof(ulong);

    private static bool IsIntegralType(Type type)
        => type == typeof(byte) || type == typeof(sbyte)
            || type == typeof(short) || type == typeof(ushort)
            || type == typeof(int) || type == typeof(uint)
            || type == typeof(long) || type == typeof(ulong);

    private static bool IsFractionalNumeric(object value)
        => value is float or double or decimal;

    private static bool TryGetValue(IReadOnlyDictionary<string, object?> values, string name, out object? value)
    {
        if (values.TryGetValue(name, out value)) return true;
        foreach (var pair in values)
        {
            if (string.Equals(pair.Key, name, StringComparison.OrdinalIgnoreCase))
            {
                value = pair.Value;
                return true;
            }
        }

        value = null;
        return false;
    }

    /// <summary>
    /// Called by generated code to register compile-time relationship candidates.
    /// These candidates are shape-only hints; <see cref="SchemaOptions"/> remains
    /// the runtime authority that applies naming policy, table names, and overrides.
    /// </summary>
    public static void RegisterRelationshipCandidates(params RelationshipCandidate[] candidates)
    {
        foreach (var candidate in candidates)
            _relationshipCandidates.Add(candidate);
    }

    internal static IReadOnlyList<RelationshipCandidate> RelationshipCandidates => _relationshipCandidates.ToArray();

    // Shim type lookup for IEntity<TId> CBOR deserialization
    private static readonly ConcurrentDictionary<Type, Type> _shimTypes = new();

    /// <summary>
    /// Registers a shim type for an IEntity{TId} type.
    /// Called by generated shim static constructors.
    /// </summary>
    public static void RegisterShimType<TEntity>(Type shimType)
    {
        _shimTypes[typeof(TEntity)] = shimType;
    }

    /// <summary>
    /// Gets the registered shim type for the given entity type, or null if none.
    /// </summary>
    public static Type? GetShimType(Type entityType)
    {
        _shimTypes.TryGetValue(entityType, out var shimType);
        return shimType;
    }
}
